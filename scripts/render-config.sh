#!/bin/bash
# Substitute .env values into the config files that compose mounts (safe to re-run).
#
# Why this exists:
#   - Traefik accepts its static config from exactly one of file, environment or
#     arguments, and does not expand environment variables inside the file. Values that
#     differ per host (ACME_EMAIL, EDGE_NETWORK) therefore cannot be written into
#     traefik/traefik.yml directly and are substituted here.
#   - The CrowdSec LAPI key cannot be written into the dynamic config for the same reason.
#     It is written to a file for the bouncer plugin's crowdsecLapiKeyFile option.
#
# Output (none of it tracked by git):
#   traefik/generated/traefik.yml     static config
#   traefik/generated/lapi-key        CrowdSec LAPI key (mode 600)
#   crowdsec/generated/allowlist.tsv  allowlist source of truth (IP<TAB>note), edited by ban.sh
#   crowdsec/generated/whitelist.yaml the CrowdSec parser whitelist built from it
#
# Usage:
#   render-config.sh            # everything
#   render-config.sh allowlist  # rebuild only the allowlist (called by ban.sh)

set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
ROOT_DIR="$(dirname "$SCRIPT_DIR")"
cd "$ROOT_DIR"

ALLOW_TSV="crowdsec/generated/allowlist.tsv"
ALLOW_YAML="crowdsec/generated/whitelist.yaml"

# This script runs both as the deploy user (make update) and as root (the systemd
# timers via ban.sh). Root runs must not leave root-owned files behind, or the next
# make update fails with Permission denied. Called at the end of every entry point.
fix_ownership() {
  if [ "$(id -u)" = 0 ]; then
    chown -R --reference="$ROOT_DIR" crowdsec/generated traefik/generated 2>/dev/null || true
  fi
}

# Convert the allowlist (allowlist.tsv) into a CrowdSec parser whitelist.
# It is dropped at the parser stage, so an allowlisted IP never produces a decision.
render_allowlist() {
  mkdir -p crowdsec/generated
  [ -f "$ALLOW_TSV" ] || : > "$ALLOW_TSV"

  local ips=() cidrs=() ip note
  while IFS=$'\t' read -r ip note || [ -n "${ip:-}" ]; do
    ip="${ip%%$'\r'}"
    [ -n "$ip" ] || continue
    case "$ip" in
      \#*) continue ;;
      */*) cidrs+=("$ip") ;;
      *) ips+=("$ip") ;;
    esac
  done < "$ALLOW_TSV"

  {
    echo "# Generated by scripts/render-config.sh. Do not edit directly."
    echo "# Source of truth: crowdsec/generated/allowlist.tsv. Edit with make ban CMD=allow|disallow"
    echo "name: edge/allowlist"
    echo 'description: "IPs allowlisted by operations (never blocked)"'
    echo "whitelist:"
    echo '  reason: "edge allowlist"'
    if [ "${#ips[@]}" -gt 0 ]; then
      echo "  ip:"
      for ip in "${ips[@]}"; do printf '    - "%s"\n' "$ip"; done
    fi
    if [ "${#cidrs[@]}" -gt 0 ]; then
      echo "  cidr:"
      for ip in "${cidrs[@]}"; do printf '    - "%s"\n' "$ip"; done
    fi
    # CrowdSec refuses to start on a whitelist node with no ip/cidr/expression
    # ("Node is empty or invalid"). With an empty allowlist, emit an expression that
    # never matches so the file stays valid.
    if [ "${#ips[@]}" -eq 0 ] && [ "${#cidrs[@]}" -eq 0 ]; then
      echo "  expression:"
      echo '    - "false"'
    fi
  } > "$ALLOW_YAML.tmp"
  mv "$ALLOW_YAML.tmp" "$ALLOW_YAML"
}

if [ "${1:-all}" = "allowlist" ]; then
  render_allowlist
  fix_ownership
  echo "Allowlist applied: $ALLOW_YAML"
  exit 0
fi

# ---- Read .env and check the required keys ---------------------------------
if [ ! -f .env ]; then
  echo ".env is missing (run cp .env.example .env, then make env)" >&2
  exit 1
fi
set -a; . ./.env; set +a

fail=0
for key in ACME_EMAIL CROWDSEC_BOUNCER_KEY; do
  if [ -z "${!key:-}" ]; then
    echo "$key is not set in .env" >&2
    fail=1
  fi
done
[ "$fail" -eq 0 ] || { echo "Set it with make env and run again" >&2; exit 1; }

# The shared network name; must always match the compose default (${EDGE_NETWORK:-edge})
EDGE_NETWORK="${EDGE_NETWORK:-edge}"

# ---- Traefik static config --------------------------------------------------
mkdir -p traefik/generated
# In a sed replacement, & means "the matched text", so escape it
esc_email="${ACME_EMAIL//&/\\&}"
esc_network="${EDGE_NETWORK//&/\\&}"
sed -e "s|__ACME_EMAIL__|${esc_email}|g" \
    -e "s|__EDGE_NETWORK__|${esc_network}|g" \
    traefik/traefik.yml > traefik/generated/traefik.yml.tmp
if grep -q '__ACME_EMAIL__\|__EDGE_NETWORK__' traefik/generated/traefik.yml.tmp; then
  rm -f traefik/generated/traefik.yml.tmp
  echo "Substitution into the static config failed (ACME_EMAIL / EDGE_NETWORK)" >&2
  exit 1
fi
mv traefik/generated/traefik.yml.tmp traefik/generated/traefik.yml
chmod 644 traefik/generated/traefik.yml

# ---- CrowdSec LAPI key ------------------------------------------------------
umask 077
printf '%s' "$CROWDSEC_BOUNCER_KEY" > traefik/generated/lapi-key.tmp
mv traefik/generated/lapi-key.tmp traefik/generated/lapi-key
chmod 600 traefik/generated/lapi-key
umask 022

# ---- Directories ------------------------------------------------------------
# Create acme.json up front. Without it Traefik 3.7 fails with
# "unable to get ACME account: open /acme/acme.json: no such file or directory",
# drops the resolver from its list and starts without obtaining a single certificate
# (acme-http@internal then fails with "HTTP challenge is not enabled").
# An empty file is fine; Traefik treats it as a fresh registration.
mkdir -p traefik/acme
chmod 700 traefik/acme
if [ ! -f traefik/acme/acme.json ]; then
  umask 077
  : > traefik/acme/acme.json
  umask 022
fi
chmod 600 traefik/acme/acme.json
mkdir -p logs/traefik

# ---- Dashboard (optional) ---------------------------------------------------
# When DASHBOARD_HOST and DASHBOARD_AUTH are set in .env, publish the Traefik
# dashboard on that FQDN behind basic auth (api@internal, HTTPS via the default
# resolver). Both empty (the default) means no route exists at all.
# The file lives in the watched dynamic dir but is generated and untracked.
DASH_FILE="traefik/dynamic/generated-dashboard.yml"
if [ -n "${DASHBOARD_HOST:-}" ] && [ -n "${DASHBOARD_AUTH:-}" ]; then
  {
    echo "# Generated by scripts/render-config.sh from DASHBOARD_HOST / DASHBOARD_AUTH in .env."
    echo "# Do not edit directly; empty both keys and run make render to remove the route."
    echo "http:"
    echo "  routers:"
    echo "    dashboard:"
    echo "      rule: Host(\`${DASHBOARD_HOST}\`)"
    echo "      entrypoints: [websecure]"
    echo "      service: api@internal"
    echo "      middlewares: [dashboard-auth]"
    echo "  middlewares:"
    echo "    dashboard-auth:"
    echo "      basicAuth:"
    echo "        users:"
    echo "          - \"${DASHBOARD_AUTH}\""
  } > "$DASH_FILE.tmp"
  mv "$DASH_FILE.tmp" "$DASH_FILE"
  chmod 600 "$DASH_FILE"
  echo "Dashboard route enabled (${DASHBOARD_HOST})"
else
  rm -f "$DASH_FILE"
fi

render_allowlist
fix_ownership

echo "Config generated (traefik/generated, crowdsec/generated)"
